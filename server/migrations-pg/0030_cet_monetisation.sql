DECLARE
  t text;
  corps text;
  i_cles text;
  u_cles text;
  d_cles text;
BEGIN
  FOREACH t IN ARRAY ARRAY['monetisations_cet']
  LOOP
    EXECUTE format('CREATE TRIGGER revision AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION revision_suivante()', t);
    i_cles := 'SELECT (id)::text AS k FROM nouvelles';
    u_cles := 'SELECT (id)::text AS k FROM nouvelles UNION SELECT (id)::text FROM anciennes';
    d_cles := 'SELECT (id)::text AS k FROM anciennes';
