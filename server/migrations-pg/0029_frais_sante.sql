-- lignes_frais_sante : déclencheurs posés comme pour les tables de 0020, sans clé. lignes_frais : déclencheurs gardés,
-- fonctions remplacées pour inscrire les clés (même corps que celui des tables inscrites par clé de 0020).
DO $$
DECLARE
  t text;
  corps text;
  i_cles text;
  u_cles text;
  d_cles text;
BEGIN
  FOREACH t IN ARRAY ARRAY['lignes_frais_sante', 'lignes_frais']
  LOOP
    IF t IN ('lignes_frais_sante') THEN
      i_cles := 'SELECT NULL::text AS k';
      u_cles := i_cles;
      d_cles := i_cles;
    ELSE
      i_cles := 'SELECT (id)::text AS k FROM nouvelles';
      u_cles := 'SELECT (id)::text AS k FROM nouvelles UNION SELECT (id)::text FROM anciennes';
      d_cles := 'SELECT (id)::text AS k FROM anciennes';
    END IF;
    corps := $f$
DECLARE r bigint; c bigint;
BEGIN
  SELECT n INTO r FROM revision;
  SELECT count(*) INTO c FROM (SELECT 1 FROM %2$s LIMIT 1001) x;
  IF c > 1000 THEN
    INSERT INTO changements (n, tbl, pk) VALUES (r, TG_TABLE_NAME, NULL);
  ELSIF c > 0 THEN
    INSERT INTO changements (n, tbl, pk) SELECT r, TG_TABLE_NAME, x.k FROM (%1$s) x;
  END IF;
  RETURN NULL;
END
$f$;
    EXECUTE format('CREATE OR REPLACE FUNCTION %I() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS %L', 'revision_lignes_' || t || '_i',
      format(corps, i_cles, 'nouvelles'));
    EXECUTE format('CREATE OR REPLACE FUNCTION %I() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS %L', 'revision_lignes_' || t || '_u',
      format(corps, u_cles, 'nouvelles'));
    EXECUTE format('CREATE OR REPLACE FUNCTION %I() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS %L', 'revision_lignes_' || t || '_d',
