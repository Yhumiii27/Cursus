SELECT t."emp_id", t."h", t."id", t."delivree", t."par", CASE WHEN h."validite" > 0 THEN (t."delivree" + make_interval(months => h."validite"))::date END,
	(now() AT TIME ZONE 'Europe/Paris')::date
FROM "hab_titres" t LEFT JOIN "habilitations" h ON h."id" = t."h"
