-- server/src/db.ts (50 tables, noms inchangés en snake_case). Remplace infra/postgres/cursus/schema.sql de Matrix
-- (28 tables, état du 15/10/2026) ; écarts relevés dans docs/ARCHITECTURE.md, « Accès à la base : PostgreSQL ».
--
-- Appliquée au démarrage par server/src/db-pg.ts (journal schema_migrations, verrou hashtext('cursus.migrations') pris
-- avant de lire le journal, une transaction par fichier), en tant que cursus_app, propriétaire du schéma. Noms non
-- qualifiés : ils résolvent dans le search_path de la connexion (search_path=cursus, posé par le pool et sur le rôle).
-- Aucun droit n'est accordé ici : sur le serveur, le déclencheur droits_ddl du socle donne à matrix_lecture les
-- colonnes autorisées dès la création (infra/postgres/init/03-droits.sql de Matrix). Ce fichier ne se modifie plus
-- une fois publié : un changement de schéma passe par une nouvelle migration NNNN_<objet>.sql.
--
-- Types, d'après les valeurs écrites par le code (jeu de démonstration et les 856 tests de npm test) :
--   texte « AAAA-MM-JJ »                    → date (le pilote les rend en chaîne : parseur du type 1082)
--   horodatage ISO (toISOString)            → timestamp with time zone (rendu par toISOString : parseur 1184)
--   int                                     → integer
--   real (heures, jours, soldes, montants)  → numeric, sans arrondi : restitue exactement le nombre JavaScript
--   bool (0/1)                              → boolean NOT NULL DEFAULT false (une valeur absente vaut faux, comme
--                                             la lecture de SQLite)
--   json (texte)                            → json : texte conservé tel quel, ordre des clés compris (jsonb les
--                                             trierait : contenu des lots de paie, comptes rendus, journal)
--   clé AUTOINCREMENT                       → integer GENERATED BY DEFAULT AS IDENTITY (identifiants fixés par la
--                                             démonstration et gardés à la reprise ; séquence recalée par l'adaptateur)
--   ordre rowid de SQLite                   → colonne rang (formations, habilitations, destinations, projets,
--                                             équipes, chantiers), départage des tris de Db.all
--
-- Contraintes : clés étrangères des références contrôlées par server/src/integrite.ts (REFERENCES), avec
-- ON UPDATE CASCADE sur les codes texte ; unicités de TABLES ; CHECK des domaines fermés de shared/types.ts que tous
-- les chemins d'écriture respectent. Pas de CHECK de forme sur les colonnes JSON ni de règle entre colonnes (dates
-- dans l'ordre, régime de temps) : le code ne les garantit pas partout (« dans le doute, pas de CHECK »).
